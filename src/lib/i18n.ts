const DICTS: Record<Lang, Record<TKey, string>> = { en, ar };

export function translate(lang: Lang, key: TKey, params: Record<string, string | number> = {}): string {
  const s = DICTS[lang][key] ?? en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, p) => (p in params ? String(params[p]) : `{${p}}`));
}

export function hasKey(key: string): key is TKey {
  return key in en;
}

const LOCALE: Record<Lang, string> = { en: "en-GB", ar: "ar" };

/** Western digits and the Gregorian calendar in both languages, so numbers read the same. */
export function formatNumber(lang: Lang, n: number): string {
  return new Intl.NumberFormat(LOCALE[lang] + "-u-nu-latn", { maximumFractionDigits: 2 }).format(n);
}

